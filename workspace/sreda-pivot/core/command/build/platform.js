'use strict';

/**
 * Collect кладёт в platform restmodule/memorysave (строки) и structure/core (объекты).
 * path.join принимает только строки — объекты пропускаем.
 */
const fs = require('fs');
const path = require('path');

function pickStrings(platform) {
    const out = {};
    if (!platform || typeof platform !== 'object') {
        return out;
    }
    for (const [key, value] of Object.entries(platform)) {
        if (typeof value === 'string' && value.trim()) {
            out[key] = value;
        }
    }
    return out;
}

function writeIndex(platform) {
    const cfg = pickStrings(platform);
    const restmodule = cfg.restmodule || 'rest-express';
    const memorysave = cfg.memorysave || 'memorysave-storage-node-cache';
    const extRoot = path.join(process.cwd(), 'ext_modules');
    const versions = {};
    if (fs.existsSync(extRoot)) {
        for (const name of fs.readdirSync(extRoot)) {
            const pkgPath = path.join(extRoot, name, 'package.json');
            if (!fs.existsSync(pkgPath)) {
                continue;
            }
            try {
                const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
                versions[name] = String(pkg.version || '0.0.0');
            } catch (e) {
                // skip
            }
        }
    }
    const restIdent = restmodule
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
        .join('');
    const memIdent = memorysave
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
        .join('');
    const body = `/**
 * Autogenerated file. Don't change it manualy.
 */

// ---------------- restmodule: ${restmodule} ----------------
const ${restIdent} = require("./${restmodule}");
// ---------------- memorysave: ${memorysave} ----------------
const ${memIdent} = require("./${memorysave}");

sreda.restmodule = ${restIdent};
sreda.memorysave = ${memIdent};

sreda.versions = ${JSON.stringify(versions, null, 4)};

module.exports = {};
`;
    fs.writeFileSync(path.join(extRoot, 'index.js'), body);
}

module.exports = function platform(a, b) {
    const cfg =
        b && typeof b === 'object' && (b.restmodule || b.memorysave)
            ? b
            : a && typeof a === 'object'
              ? a
              : {};
    const strings = pickStrings(cfg);
    for (const value of Object.values(strings)) {
        path.join(process.cwd(), 'ext_modules', value);
    }
    writeIndex(cfg);
};
