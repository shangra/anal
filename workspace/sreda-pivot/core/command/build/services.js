'use strict';

/**
 * Пишет ext_modules/services.js.
 * Имена const — полный путь от services/ (включая metadata/connectors),
 * чтобы два AbstractConnector.js не давали один Identifier.
 */
const fs = require('fs');
const path = require('path');
const { serviceConstName, uniqueName, toPascal } = require('./uniqueIdent');

const root = process.cwd();
const extRoot = path.join(root, 'ext_modules');

function walkJs(dir, acc = []) {
    if (!fs.existsSync(dir)) {
        return acc;
    }
    for (const name of fs.readdirSync(dir)) {
        if (
            name === 'node_modules' ||
            name === '__tests__' ||
            name === '__test__' ||
            name === '__mocks__'
        ) {
            continue;
        }
        const full = path.join(dir, name);
        if (fs.statSync(full).isDirectory()) {
            walkJs(full, acc);
            continue;
        }
        if (name.endsWith('.js') && !/\.(test|spec)\.js$/i.test(name)) {
            acc.push(full);
        }
    }
    return acc;
}

function listModules() {
    return fs
        .readdirSync(extRoot)
        .filter((name) => {
            const dir = path.join(extRoot, name);
            return (
                fs.statSync(dir).isDirectory() &&
                fs.existsSync(path.join(dir, 'package.json'))
            );
        })
        .sort();
}

function writeServicesJs() {
    const used = new Set();
    const requires = [];
    const blocks = [];

    for (const modName of listModules()) {
        const modDir = path.join(extRoot, modName);
        let pkg = {};
        try {
            pkg = JSON.parse(
                fs.readFileSync(path.join(modDir, 'package.json'), 'utf8')
            );
        } catch (e) {
            continue;
        }
        if (pkg.enabled === false) {
            continue;
        }

        const serviceDir = path.join(modDir, 'services');
        const files = walkJs(serviceDir);
        const rows = files.map((abs) => {
            const rel = path.relative(serviceDir, abs);
            const ident = uniqueName(
                serviceConstName(modName, rel),
                used
            );
            return {
                ident,
                key: rel
                    .replace(/\\/g, '/')
                    .replace(/\.js$/i, '')
                    .split('/')
                    .map(toPascal)
                    .join(''),
                req: `./${path
                    .relative(extRoot, abs)
                    .replace(/\\/g, '/')
                    .replace(/\.js$/i, '')}`,
                abs,
            };
        });

        const byRel = {};
        for (const row of rows) {
            const rel = path
                .relative(modDir, row.abs)
                .replace(/\\/g, '/')
                .replace(/\.js$/i, '');
            for (const alias of [rel, `/${rel}`, rel.toLowerCase()]) {
                byRel[alias] = row.ident;
            }
        }

        if (rows.length) {
            requires.push(`/** ${modName} */`);
            for (const row of rows) {
                requires.push(`const ${row.ident} = require("${row.req}");`);
            }
        }

        const serviceMap = rows
            .map((row) => `            ${row.key}: ${row.ident}`)
            .join(',\n');

        const hooks = {};
        for (const [hookKey, spec] of Object.entries(pkg.extensions || {})) {
            if (!spec || typeof spec.class !== 'string' || !spec.function) {
                continue;
            }
            const rel = spec.class
                .replace(/^[\\/]/, '')
                .replace(/\\/g, '/')
                .replace(/\.js$/i, '');
            const classIdent =
                byRel[rel] ||
                byRel[rel.toLowerCase()] ||
                byRel[`services/${rel.replace(/^services\//i, '')}`.toLowerCase()];
            if (!classIdent) {
                continue;
            }
            hooks[hookKey] = hooks[hookKey] || [];
            hooks[hookKey].push({ classIdent, fn: spec.function });
        }
        const hookLines = Object.entries(hooks)
            .map(([key, list]) => {
                const items = list
                    .map(
                        (item) =>
                            `                {\n                    class: ${item.classIdent},\n                    function: "${item.fn}"\n                }`
                    )
                    .join(',\n');
                return `            "${key}": [\n${items}\n            ]`;
            })
            .join(',\n');

        blocks.push(
            `    "${modName}": {\n        services: {${
                serviceMap ? `\n${serviceMap}\n        ` : ''
            }},\n        hooks: {${hookLines ? `\n${hookLines}\n        ` : ''}},\n    }`
        );
    }

    const out = `/**
 * Autogenerated file. Don't change it manualy.
 */

/** -------------------- services -------------------- */

${requires.join('\n')}

module.exports = {
${blocks.join(',\n')}
};
`;
    fs.writeFileSync(path.join(extRoot, 'services.js'), out);
}

module.exports = function collectServices() {
    writeServicesJs();
};

if (require.main === module) {
    writeServicesJs();
}
