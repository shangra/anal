// Set this to true for production
const doCache = false;

// Name our cache
const CACHE_NAME = 'SberPWA';

const assets = ['/', '/index.html', '/static/js/main.chunk.js'];

// Delete old caches that are not our current one!
self.addEventListener('activate', (event) => {
    const cacheWhitelist = [CACHE_NAME];
    event.waitUntil(
        caches.keys().then((keyList) =>
            Promise.all(
                keyList.map((key) => {
                    if (!cacheWhitelist.includes(key)) {
                        console.log(`Deleting cache: ${key}`);
                        return caches.delete(key);
                    }
                }),
            ),
        ),
    );
});

// The first time the user starts up the PWA, 'install' is triggered.
self.addEventListener('install', (event) => {
    if (doCache) {
        event.waitUntil(
            caches.open(CACHE_NAME).then((cache) => {
                cache.addAll(assets);
                // Get the assets manifest so we can see what our js file is named
                // This is because webpack hashes it
                fetch('asset-manifest.json')
                    .then((response) => {
                        response.json();
                    })
                    .then((assets) => {
                        // Open a cache and cache our files
                        // We want to cache the page and the main.js generated by webpack
                        // We could also cache any static assets like CSS or images
                        console.log('assets', assets);
                        const urlsToCache = [
                            '/',
                            // assets["main.js"]
                        ];
                        cache.addAll(urlsToCache);
                        console.log('cached', urlsToCache);
                    });
            }),
        );
    }
});

const getNonCachedURLs = () => {
    const urls = ['/api/dynpage/settings/usermenu.json', '/api/auth/logout', '/api/auth/login', '/api/users/getuserdata/user'];
    return urls;
};

const inOnLine = () => navigator.onLine;

// When the webpage goes to fetch files, we intercept that request and serve up the matching files
// if we have them
self.addEventListener('fetch', (event) => {
    if (doCache) {
        // console.log('event.request', event.request);
        let cacheOff = false;
        if (inOnLine()) {
            const listNonCached = getNonCachedURLs();
            if (listNonCached.indexOf(event.request.url) > -1 && event.request.method !== 'basic') {
                // Если интернет доступен и это не запрос из кеша и список некешируемых данных, то надо запросить новые данные

                cacheOff = true;
                return fetch(event.request).then((response) => {
                    if (!response || response.status !== 200 || response.type !== 'basic') {
                        return response;
                    }
                });
            }
        }

        if (!cacheOff) {
            event.respondWith(
                caches.match(event.request).then((response) => {
                    if (response) {
                        // console.log('response event', response);
                        return response;
                    }

                    return fetch(event.request).then((response) => {
                        // Check if we received a valid response
                        if (!response || response.status !== 200 || response.type !== 'basic') {
                            return response;
                        }

                        const responseToCache = response.clone();
                        caches.open(CACHE_NAME).then((cache) => {
                            cache.put(event.request, responseToCache);
                        });
                        return response;
                    });
                }),
            );
        }
    }
});
