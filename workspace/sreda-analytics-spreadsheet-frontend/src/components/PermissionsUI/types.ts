export enum EOperation {
    VIEW = 'view',
    READ = 'read',
    WRITE = 'write',
    DELETE = 'delete',
}

export interface ICardInfo {
    /** Идентификатор сущности для изменения доступных операций */
    id: string;
    /** Для пользователей можно задать аватарку */
    avatar?: string;
    /** Основной текст сущности (ФИО, название и т.д.) */
    title: string;
    /** Дополнительный текст сущности (Позиция, роль, оригинальное название и т.д.) */
    subtitle?: string;
    /** Массив доступных операций для сущности */
    value: EOperation[];
    /**
     * Блокировка изменения операций для сущности.
     * - `true` — блокирует всю карточку целиком.
     * - `EOperation[]` — блокирует только перечисленные операции (нельзя добавить/повысить).
     * - `false` / `undefined` — карточка полностью активна.
     */
    disabled?: boolean | EOperation[];
}
